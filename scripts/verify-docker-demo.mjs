import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
const dir='test-results/docker-demo';
const events=readFileSync(`${dir}/transcript.jsonl`,'utf8').trim().split('\n').map(JSON.parse);
const result=e=>e.response.structuredContent?.result;
const calls=tool=>events.filter(e=>e.request.tool===tool);
const request=key=>calls('run_command').find(e=>e.request.arguments.clientRequestId===key);
const before=result(request('codex-docker-before-001'));
const after=result(request('codex-docker-after-001'));
assert.equal(before.exitCode,1);assert.equal(after.exitCode,0);assert.equal(before.sessionId,after.sessionId);
const outputs=calls('read_output');
const output=(id,stream)=>result(outputs.find(e=>e.request.arguments.commandId===id&&e.request.arguments.stream===stream));
assert.match(output(before.id,'stderr').content,/FAILED \(failures=2\)/);
assert.match(output(after.id,'stderr').content,/Ran 5 tests[\s\S]*OK/);
assert.match(output(after.id,'stdout').content,/marker=subscription-session\ncwd=\/workspace\/project\npython_prefix=\/workspace\/project\/\.venv/);
const files=calls('read_file'),tests=files.filter(e=>e.request.arguments.path==='test_pricing.py');
assert.ok(tests.length>=2);assert.equal(result(tests[0]).version,result(tests.at(-1)).version);
const prices=files.filter(e=>e.request.arguments.path==='pricing.py');assert.notEqual(result(prices[0]).version,result(prices.at(-1)).version);
const patch=result(calls('apply_patch')[0]);assert.equal(patch.state,'applied');assert.deepEqual(patch.files.map(f=>f.path),['pricing.py']);
const repeated=calls('run_command').filter(e=>e.request.arguments.clientRequestId==='codex-docker-detached-001');
assert.equal(repeated.length,2);assert.equal(result(repeated[0]).id,result(repeated[1]).id);
assert.equal(result(files.find(e=>e.request.arguments.path==='mcp-once.txt')).content,'once');
const completed=result(calls('get_command').find(e=>result(e)?.id===result(repeated[0]).id&&result(e)?.state==='completed'));
assert.equal(completed.exitCode,0);
assert.equal(output(completed.id,'stdout').content,'startedfinished');
const list=events.find(e=>e.request.method==='tools/list');assert.equal(list.response.tools.length,14);
const inspect=JSON.parse(execFileSync('docker',['inspect','shell-mcp-demo-target'],{encoding:'utf8'}))[0];
assert.equal(inspect.State.Running,true);assert.equal(inspect.Mounts.length,1);assert.ok(inspect.Mounts[0].Source.endsWith('/target-keys'));assert.equal(inspect.Mounts[0].RW,false);
assert.equal(inspect.NetworkSettings.Ports['22/tcp'][0].HostIp,'127.0.0.1');
writeFileSync(`${dir}/before-tests.txt`,output(before.id,'stderr').content);
writeFileSync(`${dir}/after-tests.txt`,output(after.id,'stderr').content);
writeFileSync(`${dir}/session-state.txt`,output(after.id,'stdout').content);
writeFileSync(`${dir}/pricing.fixed.py`,result(prices.at(-1)).content);
writeFileSync(`${dir}/remote-change.patch`,result(calls('git_diff').at(-1)).output);
const report={status:'PASS',actor:'current Codex conversation',additionalAiApiCalls:0,nativeCodexMcpToolRegistration:'NOT RUN; SDK bridge used from current session',protocols:[...new Set(events.map(e=>e.protocol))],container:{name:inspect.Name.slice(1),id:inspect.Id,image:inspect.Image,running:true},sessionId:before.sessionId,before:{commandId:before.id,exitCode:1,tests:5,failures:2},after:{commandId:after.id,exitCode:0,tests:5,failures:0},testSourceUnchanged:true,sessionEnvironmentPreserved:true,repeatedRequestExecutedOnce:true,mcpCallCount:events.length};
writeFileSync(`${dir}/report.json`,JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report,null,2));
